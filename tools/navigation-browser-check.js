async (page) => {
  const base = new URL(page.url()).origin;
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 390, height: 844 });
  const ready = view => page.locator(`#view-${view}.active`).waitFor({ timeout: 45000 });
  const checkText = async (selector, text) => {
    const content = await page.locator(selector).innerText();
    if (!content.includes(text)) throw Error(`Missing ${text} in ${selector}`);
  };
  await page.goto(`${base}/?athlete=20190918M202510090308`);
  await ready('athlete-detail');
  await checkText('#athleteHero', '蔡廷彧');
  await page.getByRole('button', { name: '查看成长分析', exact: true }).click();
  await ready('parent-growth-report');
  await checkText('#view-parent-growth-report', '蔡廷彧 的成长报告');
  await checkText('#view-parent-growth-report', '参赛 9 场');
  await page.goBack();
  await ready('athlete-detail');
  await checkText('#athleteHero', '蔡廷彧');
  await page.goForward();
  await ready('parent-growth-report');
  await page.locator('#topBack').click();
  await ready('athlete-detail');
  checks.push('athlete → growth → browser back/forward → app back');
  await page.getByRole('button', { name: '与马潇对比', exact: true }).click();
  await ready('ai-analysis');
  await page.locator('#aiAnswer .ai-answer-card').waitFor({ timeout: 45000 });
  await checkText('#aiAnswer', '蔡廷彧 vs 马潇');
  await page.locator('#topBack').click();
  await ready('athlete-detail');
  await page.goForward();
  await ready('ai-analysis');
  await checkText('#aiAnswer', '蔡廷彧 vs 马潇');
  await page.reload();
  await ready('ai-analysis');
  await checkText('#aiAnswer', '蔡廷彧 vs 马潇');
  checks.push('comparison identity + history and refresh restoration');
  await page.goto(`${base}/?growth=20190130M202506250112`);
  await ready('parent-growth-report');
  await checkText('#view-parent-growth-report', '马潇 的成长报告');
  await checkText('#view-parent-growth-report', '参赛 14 场');
  checks.push('second athlete direct growth link uses separate records');
  await page.goto(`${base}/?competition=RZSS2034020`);
  await ready('competition-detail');
  await page.getByText('查看全部 84 个项目', { exact: true }).click();
  await page.locator('#view-competition-detail details summary').filter({ hasText: /U10/ }).click();
  await page.locator('#view-competition-detail [data-event-code="RZSS2034020MFIU10"]').first().click();
  await ready('event-detail');
  await page.goBack();
  await ready('competition-detail');
  if (!page.url().includes('competition=RZSS2034020')) throw Error('event parent route lost');
  await page.goForward();
  await ready('event-detail');
  if (!page.url().includes('event=RZSS2034020MFIU10')) throw Error('event route lost');
  checks.push('competition → event → browser back/forward with exact entity IDs');
  await page.goto(`${base}/?tab=my`);
  await ready('my');
  await page.locator('#myPage [data-account-open-login]').first().click();
  await ready('account-login');
  await page.locator('#authPassword').fill('navigation-test-only');
  await page.locator('[data-auth-reveal]').click();
  if (await page.locator('#authPassword').getAttribute('type') !== 'text') throw Error('password reveal failed');
  await page.locator('[data-auth-mode="register"]').click();
  await checkText('#accountLoginPage', '创建你的账号');
  await page.goBack();
  await checkText('#accountLoginPage', '欢迎回来');
  await page.locator('[data-auth-mode="reset"]').click();
  await checkText('#accountLoginPage', '找回密码');
  await page.reload();
  await ready('account-login');
  await checkText('#accountLoginPage', '找回密码');
  const config = await (await page.request.get(`${base}/api/auth/config`)).json();
  if (!config.emailVerification) {
    await page.waitForFunction(() => document.querySelector('[data-auth-availability]')?.textContent.includes('暂未开放'));
    if (!await page.locator('[data-auth-send-code]').isDisabled()) throw Error('unconfigured verification must be disabled');
  }
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  if (overflow) throw Error('mobile account page overflows');
  checks.push('my → login/register/reset + back and reload; truthful capability notice; mobile layout');
  if (errors.length) throw Error(errors.join('\n'));
  await page.screenshot({ path: 'analysis-output/navigation-account-mobile.png', fullPage: true });
  return { ok: true, base, checks, scriptErrors: errors };
}
