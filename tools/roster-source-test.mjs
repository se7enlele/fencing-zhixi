import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { buildRegistrationRosterReport } from './parse-registration-roster.mjs';
import { rosterRequest, assertRosterRefresh } from './roster-source.mjs';
import { buildPreEventCompetitions } from './pre-event-data.mjs';
import { runIsolatedTask } from './scheduled-sync.mjs';
import { hasDetailedScore } from './sync-platform-data.mjs';
const item={sourceSportId:101209,sourceSportCode:'RZSS2036013',sourceEventCode:'RZSS2036013MFIU8',itemName:'U8男子花剑个人',genderCode:'M',weaponCode:'F',ageGroupCode:'U8',itemTypeCode:'I',startDate:'2025-10-17 10:00:00',endDate:'2025-10-19 10:00:00',participantCount:75};
const event={sportId:101209,sportCode:item.sourceSportCode,sportName:'御剑紫金杯',startDate:'2026-10-24 08:00:00',endDate:'2026-10-25 18:00:00',sigupactive:'1'};
const request=rosterRequest(item,event,{proxyBase:'https://pipeline.example',rosterApi:'auto'});
assert.equal(request.url,'https://pipeline.example/matchregister/v3/signup/conditionQuery');
assert.deepEqual(request.body,{sportId:'101209',registerType:'athlete',gender:'M',weapon:'F',ecode:'U8'});
assert.throws(()=>rosterRequest({...item,ageGroupCode:null},event,{proxyBase:'x'}),/Missing/);
const source={sourceType:'condition-query',sportCode:event.sportCode,eventCode:item.sourceEventCode,eventName:item.itemName,sportName:event.sportName,importedAt:'2026-09-30T12:00:00Z'};
const report=buildRegistrationRosterReport({code:0,data:[{athleteName:'同名选手',shortName:'俱乐部甲',gender:'男',status:'审核通过'},{athleteName:'同名选手',shortName:'俱乐部乙',gender:'男',status:'待缴费'}]},source);
assert.equal(report.normalized.records[0].approveStatus,'审核通过');
assert.equal(report.normalized.records[1].approveStatus,'待缴费');
assert.notEqual(report.normalized.records[0].dedupeKey,report.normalized.records[1].dedupeKey);
assert.equal(report.summary.athleteCount,2);
assert.equal(report.summary.clubCount,2);
assert.equal(report.normalized.records[0].registerCode,null,'never manufacture a registered identity from display-only roster');
assertRosterRefresh(report);
assert.throws(()=>assertRosterRefresh(buildRegistrationRosterReport({code:0,data:[]},source),report),/existing roster retained/);
assert.throws(()=>buildRegistrationRosterReport({code:403,data:[]},source),/403/);
const old=buildRegistrationRosterReport({data:[{athleteName:'已退出选手',shortName:'俱乐部甲'}]}, {...source,sourceType:'legacy-roster',importedAt:'2026-09-29T12:00:00Z'});
const competition=buildPreEventCompetitions({projectLists:[{report:{normalizedItems:[item]}}],rosterBatches:[{report:old},{report}],platformEventLists:[{report:{normalizedEvents:[event]}}]})[0];
assert.equal(competition.items[0].roster.length,2,'latest whole-list roster supersedes stale legacy pages');
assert.equal(competition.items[0].rosterStatus,'complete');
assert.equal(competition.items[0].openDate,null,'2025 template project date is not shown as 2026 schedule');
assert.equal(competition.items[0].status,'registration');
assert.equal(competition.dateLabel,'2026.10.24 / 2026.10.25');
assert.equal(competition.insights.summaryCards[1].value,2,'capacity is not a registration count');
assert.equal(hasDetailedScore({normalized:{eliminationMatches:[{}]}}),true);
assert.equal(hasDetailedScore({normalized:{classment:[{}]}}),false);
const dir=await mkdtemp(path.join(os.tmpdir(),'fencing-sync-isolation-'));
try {
  const outputDir=path.join(dir,'data');await mkdir(outputDir);
  const file=`projectlist-${event.sportId}-analysis.json`;await writeFile(path.join(outputDir,file),'OLD');
  const task={type:'pre-event-roster',sportId:event.sportId,sportCode:event.sportCode,scriptArgs:['script','--output-dir',outputDir]};
  const args={outputDir,reportDir:path.join(dir,'reports')};
  const failed=await runIsolatedTask(task,args,async staged=>{await writeFile(path.join(staged.scriptArgs[2],file),'PARTIAL');return{...staged,ok:false};});
  assert.equal(await readFile(path.join(outputDir,file),'utf8'),'OLD','failed task cannot overwrite public source files');
  assert.deepEqual(failed.committedFiles,[]);
  const successful=await runIsolatedTask(task,args,async staged=>{await writeFile(path.join(staged.scriptArgs[2],file),'{"ok":true}');return{...staged,ok:true};});
  assert.equal(await readFile(path.join(outputDir,file),'utf8'),'{"ok":true}');
  assert.deepEqual(successful.committedFiles,[file]);
}finally{await rm(dir,{recursive:true,force:true});}
console.log('certified roster, schedule conflicts and isolated sync regression checks passed');
